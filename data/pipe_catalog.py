def get_pipe_type_names():
    return sorted(PIPE_CATALOG.keys())

def get_steel_options_for_diameter(type_name, diameter):
    catalog = PIPE_CATALOG[type_name]
    options = catalog.get("options", [])
    return [o for o in options if abs(o["d"] - diameter) < 1e-9]

def get_pe_option(sdr, diameter):
    """Ищет конкретную трубу ПЭ в каталоге по SDR и диаметру"""
    catalog = PIPE_CATALOG.get(f"ПЭ-100 SDR {sdr}")
    if not catalog:
        return None
    for o in catalog["options"]:
        if abs(o["d"] - diameter) < 1e-9:
            return o
    return None

def get_pe_params(sdr, diameter):
    """
    Возвращает кортеж (толщина, шероховатость, минимальный радиус изгиба)
    для ПЭ трубы по SDR и наружному диаметру.
    Совместимость со старым кодом.
    """
    option = get_pe_option(sdr, diameter)
    if not option:
        # если точного диаметра нет, можно вернуть расчётное значение,
        # но лучше явно сообщить об ошибке или вернуть None
        return None, None, None
    return option["t"], option["rough"], option["r_min"]

def get_default_params(type_name, diameter, wall=None):
    """
    Возвращает словарь с параметрами трубы.
    Теперь включает weight_kg_m и price_rub_m!
    """
    catalog = PIPE_CATALOG[type_name]
    
    if catalog["sdr"] is not None:
        # Для ПЭ берем реальные данные из options
        option = get_pe_option(catalog["sdr"], diameter)
        if not option:
            return None # Если диаметра нет в прайсе
        return {
            "outer_d": option["d"], 
            "wall": option["t"], 
            "rough": option["rough"], 
            "r_min": option["r_min"],
            "weight_kg_m": option["weight_kg_m"],
            "price_rub_m": option["price_rub_m"]
        }
    else:
        # Для стали
        filtered = get_steel_options_for_diameter(type_name, diameter)
        if not filtered:
            return None
        
        # Если для стали не задана стена, берем первую попавшуюся
        if wall is None:
            o = filtered[0]
        else:
            o = next((opt for opt in filtered if abs(opt["t"] - wall) < 1e-9), filtered[0])
            
        return {
            "outer_d": o["d"], 
            "wall": o["t"], 
            "rough": o["rough"], 
            "r_min": o["r_min"],
            "weight_kg_m": o.get("weight_kg_m", 0.0),
            "price_rub_m": o.get("price_rub_m", 0.0)
        }